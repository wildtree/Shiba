def big_pieces(rows):
    """48x24 を 16x8 の 9 枚に。何も描かない枚は None。"""
    out = []
    for ry in range(3):
        for rx in range(3):
            piece = [rows[ry * 8 + k][rx * 16:(rx + 1) * 16] for k in range(8)]
            out.append(piece if any(c != '.' for r in piece for c in r) else None)
    return out


