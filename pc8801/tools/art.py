def logo_layer(dx, dy):
    """1 ビットの絵 (LOGO_W バイト x LOGO_H 行)。dx, dy だけずらして描く。"""
    W = LOGO_W * 8
    canvas = [[0] * W for _ in range(LOGO_H)]
    ox = LOGO_LEFT % 8 + dx
    for k, ch in enumerate(LOGO_TEXT):
        glyph = FONT[ch]
        y = dy
        for gy, h in enumerate(LOGO_ROWS):
            for gx in range(8):
                if glyph[gy][gx] != '.':
                    for yy in range(y, y + h):
                        for xx in range(LOGO_SX):
                            canvas[yy][ox + (k * 8 + gx) * LOGO_SX + xx] = 1
            y += h
    out = bytearray()
    for row in canvas:
        for b in range(LOGO_W):
            v = 0
            for i in range(8):
                if row[b * 8 + i]:
                    v |= 0x80 >> i
            out.append(v)
    return bytes(out)


def bits(row, chars):
    hi = lo = 0
    for i, c in enumerate(row[:8]):
        if c in chars:
            hi |= 0x80 >> i
    for i, c in enumerate(row[8:16]):
        if c in chars:
            lo |= 0x80 >> i
    return hi, lo


def sprite_bytes(rows):
    """16x8 の絵を 64 バイトにする。

    1 バイト列 (8 ドット) あたり 4 バイト:
        +0 マスク        (絵があるところ)
        +1 プレーン0下地 (輪郭 | 白)
        +2 プレーン1,2下地 (白)
        +3 体            (体の色のビットが立っているプレーンに OR する)
    こうしておけば描くときに合成の計算がいらない。
    """
    out = bytearray()
    for r in rows:
        assert len(r) == 16, (len(r), r)
        mh, ml = bits(r, 'KBWY')
        bh, bl = bits(r, 'B')
        wh, wl = bits(r, 'W')
        yh, yl = bits(r, 'Y')
        kh = mh & ~(bh | wh | yh) & 0xFF    # 輪郭 = マスク - 体 - 白 - 黄
        kl = ml & ~(bl | wl | yl) & 0xFF
        out += bytes((mh, kh | wh, wh | yh, bh))   # 黄 (6) = プレーン 1,2 だけ
        out += bytes((ml, kl | wl, wl | yl, bl))
    assert len(out) == 64
    return bytes(out)


def opaque_bytes(rows, pal):
    """透明なしの絵。プレーンごとに (行 x バイト列) を並べる。

    マスクも合成もいらないので、描くときは LDI で流し込むだけになる。
    """
    w = len(rows[0]) // 8
    out = bytearray()
    for plane in range(3):
        for r in rows:
            assert len(r) == w * 8, (len(r), r)
            for c in range(w):
                v = 0
                for i, ch in enumerate(r[c * 8:(c + 1) * 8]):
                    if (pal[ch] >> plane) & 1:
                        v |= 0x80 >> i
                out.append(v)
    return bytes(out)


ROADPAL = {'A': 1, 'W': 7, '.': 0}


def road_bytes(rows):
    """道路のマス: 透明なしなので不透明形式で持つ。"""
    return opaque_bytes(rows, ROADPAL)


def style_bytes(a, b):
    """色 a と b の市松 (a == b なら単色) を 6 バイトにする。"""
    even, odd = [], []
    for p in range(3):
        ba = (a >> p) & 1
        bb = (b >> p) & 1
        even.append((0xAA if ba else 0) | (0x55 if bb else 0))
        odd.append((0x55 if ba else 0) | (0xAA if bb else 0))
    return bytes(even) + bytes(odd)


def terr_style_bytes():
    out = bytearray()
    for (a, b) in TERR_STYLES:
        out += style_bytes(a, b)
    return bytes(out)


def grass_style_bytes():
    """草: 色 0 のところに色 5 (= プレーン 0 と 2) の点を置く。"""
    out = bytearray()
    for (em, om) in GRASS_MASKS:
        out += bytes((em, 0, em))       # 偶数行 p0,p1,p2
        out += bytes((om, 0, om))       # 奇数行
    return bytes(out)


def rowaddr_bytes():
    out = bytearray()
    for y in range(25):
        a = 0xC000 + y * 8 * 80
        out += bytes((a & 0xFF, (a >> 8) & 0xFF))
    return bytes(out)


def palette_bytes():
    out = bytearray()
    for (r, g, b) in PALETTE:
        out.append(((r & 7) << 3) | (b & 7))
        out.append(0x40 | (g & 7))
    return bytes(out)


def font_bytes():
    out = bytearray()
    for i in range(FONT_COUNT):
        ch = chr(FONT_FIRST + i)
        rows = FONT.get(ch, ['........'] * 8)
        for r in rows:
            v = 0
            for j, c in enumerate(r):
                if c != '.':
                    v |= 0x80 >> j
            out.append(v)
    return bytes(out)


def split32(rows32):
    return [r[:16] for r in rows32], [r[16:] for r in rows32]


